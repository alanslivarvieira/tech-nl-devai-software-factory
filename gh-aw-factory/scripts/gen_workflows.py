"""Generate the gh-aw agentic workflows: one per (phase × engine).

gh-aw fixes ``engine:`` at compile time, so the engine chosen during the grill selects which variant the
orchestrator dispatches (``factory-<phase>-<engine>.lock.yml``).

    python gh-aw-factory/scripts/gen_workflows.py          # writes gh-aw-factory/.github/workflows/*.md
    gh aw compile                                           # then compile to *.lock.yml (run in the hub repo)
"""

from __future__ import annotations

import sys
from pathlib import Path

ENGINES = ("copilot", "claude", "codex")
OUT = Path(__file__).resolve().parents[1] / ".github" / "workflows"

PHASES = {
    "grill": {
        "writes": False,
        "comment": True,
        "ref": "base",
        "timeout": 20,
        "title": "Grill the requester into an executable contract (tests as data)",
    },
    "driver": {
        "writes": True,
        "comment": False,
        "ref": "branch",
        "timeout": 30,
        "title": "Write the assertion-free tests-as-data driver",
    },
    "plan": {
        "writes": False,
        "comment": True,
        "ref": "branch",
        "timeout": 20,
        "title": "Decompose the approved feature into a task graph",
    },
    "build": {
        "writes": True,
        "comment": False,
        "ref": "branch",
        "timeout": 60,
        "title": "Implement the plan against the frozen contract",
    },
    "audit": {
        "writes": False,
        "comment": True,
        "ref": "branch",
        "timeout": 30,
        "title": "Audit the verified change in a clean context",
    },
}

TEMPLATE = """---
# GENERATED by gh-aw-factory/scripts/gen_workflows.py — edit the generator, not this file.
name: factory-{phase}-{engine}
description: "{title} ({engine})"
run-name: "factory {phase} #${{{{ inputs.issue }}}}"
on:
  workflow_dispatch:
    inputs:
      issue:
        description: Factory issue number (hub repo)
        required: true
        type: string
      fix:
        description: Fix round (feed the latest verification report)
        required: false
        type: string
        default: "false"
permissions:
  contents: read
  issues: read
  actions: read
engine: {engine}
timeout-minutes: {timeout}
network: defaults
tools:
  github:
    toolsets: [issues, repos]
{tools}steps:
  - uses: actions/checkout@v4
  - uses: actions/setup-python@v5
    with:
      python-version: "3.12"
  - name: Install factory core
    run: pip install ./shared
  - name: Deploy the factory skills (superpowers + grill-me, pinned by factory-skills/apm.lock.yaml)
    run: python -m factory_core.skills deploy .
    env:
      FACTORY_SKILLS_DIR: factory-skills
  - name: Resolve target repository
    id: target
    run: python gh-aw-factory/scripts/step.py target-info --issue "${{{{ inputs.issue }}}}"
    env:
      GH_TOKEN: ${{{{ github.token }}}}
  - name: Read-only token for the target repository
    id: app-token
    uses: actions/create-github-app-token@v2
    with:
      app-id: ${{{{ vars.FACTORY_APP_ID }}}}
      private-key: ${{{{ secrets.FACTORY_APP_PRIVATE_KEY }}}}
      owner: ${{{{ steps.target.outputs.owner }}}}
      repositories: ${{{{ steps.target.outputs.name }}}}
      permission-contents: read
  - name: Checkout target ({ref})
    uses: actions/checkout@v4
    with:
      repository: ${{{{ steps.target.outputs.owner }}}}/${{{{ steps.target.outputs.name }}}}
      ref: ${{{{ steps.target.outputs.{ref} }}}}
      token: ${{{{ steps.app-token.outputs.token }}}}
      path: target
      fetch-depth: 0
      persist-credentials: false
  - name: Render the phase prompt (fresh context)
    run: >-
      python gh-aw-factory/scripts/context.py --phase {phase} --target target
      --issue "${{{{ inputs.issue }}}}" --fix "${{{{ inputs.fix }}}}"
    env:
      GH_TOKEN: ${{{{ github.token }}}}
{post_steps}{safe_outputs}---

# Factory · {phase}

You are one phase of an AI software factory, running in a **fresh session**. Your complete instructions
were rendered for you into `/tmp/gh-aw/factory/prompt.md`. Read that file first and follow it exactly.

- The target repository is checked out in `./target`.
- The approved tests-as-data contract lives under `./target/.factory/specs/` and is **read-only for you**: a
  guard rejects any patch that touches it, the test thresholds, CI files or adds skip markers.
- The factory skills (obra/superpowers, grill-me/grilling) are installed in this workspace; use the ones your
  instructions name.
{phase_rules}"""

WRITE_TOOLS = """  edit:
  bash: [":*"]
"""
READ_TOOLS = """  bash: ["cat", "ls", "find", "grep", "head", "tail", "wc", "git log", "git diff", "git show"]
"""
POST_STEPS = """post-steps:
  - name: Export the agent's changes as a patch (applied later by the guard step)
    if: always()
    run: |
      cd target
      git add -A
      git diff --cached --binary > /tmp/gh-aw/factory/agent.patch || true
      git diff --cached --stat
  - uses: actions/upload-artifact@v4
    if: always()
    with:
      name: factory-patch
      path: /tmp/gh-aw/factory/agent.patch
      if-no-files-found: warn
"""
SAFE_COMMENT = """safe-outputs:
  add-comment:
    target: "*"
    max: 1
"""
RULES = {
    "grill": "- Do not change any file. Talk to the human only through ONE issue comment.\n",
    "driver": "- Only create/modify files under the contract's `driver/` directory. Do not commit or push.\n",
    "plan": "- Do not change any file. Publish the plan as ONE issue comment.\n",
    "build": "- Do not commit or push: the factory applies your working-tree changes after the guard approves them.\n",
    "audit": "- Do not change any file. You have not seen how the code was built — judge only the evidence.\n",
}


def render(phase: str, engine: str) -> str:
    cfg = PHASES[phase]
    return TEMPLATE.format(
        phase=phase,
        engine=engine,
        title=cfg["title"],
        timeout=cfg["timeout"],
        ref=cfg["ref"],
        tools=WRITE_TOOLS if cfg["writes"] else READ_TOOLS,
        post_steps=POST_STEPS if cfg["writes"] else "",
        safe_outputs=SAFE_COMMENT if cfg["comment"] else "",
        phase_rules=RULES[phase],
    )


ORCHESTRATOR = """# GENERATED by gh-aw-factory/scripts/gen_workflows.py — the deterministic brain of the factory.
# Reacts to human comments and to every factory workflow completion, then dispatches the next phase.
name: factory-orchestrator
on:
  issue_comment:
    types: [created]
  workflow_run:
    types: [completed]
    workflows:
{workflows}
concurrency:
  group: factory-orchestrator-${{{{ github.event.issue.number || github.event.workflow_run.display_title }}}}
  cancel-in-progress: false
permissions:
  contents: read
  issues: write
  actions: write
jobs:
  orchestrate:
    if: github.event_name == 'workflow_run' || contains(github.event.issue.labels.*.name, 'factory')
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-python@v5
        with: {{ python-version: "3.12" }}
      - run: pip install pyyaml
      # Dispatch with an App token: runs started with GITHUB_TOKEN would not chain further workflow events.
      - id: app-token
        uses: actions/create-github-app-token@v2
        with:
          app-id: ${{{{ vars.FACTORY_APP_ID }}}}
          private-key: ${{{{ secrets.FACTORY_APP_PRIVATE_KEY }}}}
      - run: python gh-aw-factory/scripts/orchestrator.py
        env:
          GH_TOKEN: ${{{{ steps.app-token.outputs.token }}}}
          FACTORY_STALL_LIMIT: ${{{{ vars.FACTORY_STALL_LIMIT || '3' }}}}
          FACTORY_MAX_ITERATIONS: ${{{{ vars.FACTORY_MAX_ITERATIONS || '0' }}}}
          FACTORY_BOT_LOGINS: ${{{{ vars.FACTORY_BOT_LOGINS || 'github-actions[bot]' }}}}
          FACTORY_RELAY_LOGINS: ${{{{ vars.FACTORY_RELAY_LOGINS || '' }}}}
"""


def workflow_names() -> list[str]:
    return ["factory-step"] + [f"factory-{p}-{e}" for p in PHASES for e in ENGINES]


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for phase in PHASES:
        for engine in ENGINES:
            path = OUT / f"factory-{phase}-{engine}.md"
            path.write_text(render(phase, engine), encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(OUT.parents[1])}")
    orch = OUT / "factory-orchestrator.yml"
    orch.write_text(
        ORCHESTRATOR.format(workflows="\n".join(f"      - {n}" for n in workflow_names())),
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {orch.relative_to(OUT.parents[1])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

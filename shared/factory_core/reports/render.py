"""Human/agent-facing renderings of reports: gate tables, failure briefs, PR bodies, chat summaries."""

from __future__ import annotations

import csv
import io
from pathlib import Path

from ..models import IntentSpec, VerificationReport
from ..tad_runner.layout import SpecLayout

ICON = {"pass": "✅", "fail": "❌", "error": "⛔", "skip": "⏭️"}


def gates_table(report: VerificationReport) -> str:
    rows = ["| Gate | Result | Required | Summary |", "|---|---|---|---|"]
    for g in report.gates:
        rows.append(
            f"| {g.name} | {ICON[g.status]} {g.status} | {'yes' if g.required else 'no'} | "
            f"{g.summary.replace('|', '/')} |"
        )
    return "\n".join(rows)


def report_markdown(report: VerificationReport) -> str:
    head = "✅ **All gates passed**" if report.passed else "❌ **Verification failed**"
    parts = [f"### Verification — iteration {report.iteration} @ `{report.commit[:10]}`", head, "", gates_table(report)]
    if report.audit:
        parts += ["", "**Test audit**"]
        parts += [
            f"- {'🛑' if f.severity == 'blocking' else '⚠️'} `{f.category}` {f.detail}"
            + (f" ({f.file})" if f.file else "")
            for f in report.audit
        ]
    parts += ["", f"<sub>fingerprint `{report.fingerprint()}`</sub>"]
    return "\n".join(parts) + "\n"


def failure_brief(report: VerificationReport, max_chars: int = 12000) -> str:
    """What a fresh builder session gets: only the failing evidence, newest first, bounded in size."""
    parts = [
        f"# Verification failed (iteration {report.iteration})",
        "Fix the PRODUCTION code (and add/adjust unit tests) so every gate below passes.",
        "You must not modify anything under .factory/specs/, test thresholds, CI config, or skip tests.",
        "",
    ]
    for g in report.gates:
        if not g.blocking:
            continue
        parts += [f"## Gate `{g.name}` — {g.status}: {g.summary}", "```", g.details.strip()[-4000:], "```", ""]
    for f in report.audit:
        if f.severity == "blocking":
            parts += [f"## Test audit — {f.category}", f.detail, f"Suggested fix: {f.suggested_fix}", ""]
    text = "\n".join(parts)
    return text if len(text) <= max_chars else text[:max_chars] + "\n…(truncated)"


def csv_markdown(text: str, limit: int = 40) -> str:
    rows = list(csv.reader(io.StringIO(text), skipinitialspace=True))
    if not rows:
        return ""
    head, body = rows[0], rows[1:]
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in body[:limit]:
        out.append("| " + " | ".join(c.replace("|", "\\|") or " " for c in r) + " |")
    if len(body) > limit:
        out.append(f"| … {len(body) - limit} more rows |")
    return "\n".join(out)


def contract_markdown(spec_dir: Path) -> str:
    layout = SpecLayout(spec_dir)
    parts: list[str] = []
    if layout.examples.is_dir():
        for p in sorted(layout.examples.glob("*.csv")):
            parts += [f"**examples/{p.name}**", "", csv_markdown(p.read_text(encoding="utf-8")), ""]
    if layout.scenarios.is_dir():
        for p in sorted(layout.scenarios.glob("*.y*ml")):
            parts += [
                f"<details><summary>scenarios/{p.name}</summary>",
                "",
                "```yaml",
                p.read_text(encoding="utf-8").rstrip(),
                "```",
                "</details>",
                "",
            ]
    if layout.properties.exists():
        parts += [
            "<details><summary>properties.yaml</summary>",
            "",
            "```yaml",
            layout.properties.read_text(encoding="utf-8").rstrip(),
            "```",
            "</details>",
            "",
        ]
    return "\n".join(parts)


def pr_body(
    intent: IntentSpec,
    spec_dir_rel: str,
    spec_dir: Path,
    report: VerificationReport,
    iterations: int,
    manifest_hash: str,
    engine: str,
) -> str:
    acs = "\n".join(f"- **{ac.id}** — {ac.description}" for ac in intent.acceptance_criteria)
    return f"""## {intent.title}

{intent.summary}

### Acceptance criteria
{acs}

### Contract (tests as data — approved by {intent.approved_by or "n/a"}, hash-locked)
Location: `{spec_dir_rel}` · manifest root `{manifest_hash[:16]}`

{contract_markdown(spec_dir)}
### Verification (clean-context run)
{gates_table(report)}

Built by the AI software factory with **{engine}** in **{iterations}** build/verify iteration(s).

### Reviewer checklist
- [ ] The contract (tables/scenarios above) says what we want
- [ ] No changes under `.factory/specs/` other than the approved freeze commit
- [ ] Production change is readable and scoped to the intent

🤖 Generated by the AI software factory
"""


def chat_summary(report: VerificationReport) -> str:
    bad = [g for g in report.gates if g.blocking]
    if not bad:
        return f"✅ Iteration {report.iteration}: all gates green."
    return f"❌ Iteration {report.iteration}: failing " + ", ".join(f"{g.name} ({g.summary})" for g in bad)
